        "def gnn_assign(cost):",
        "    \"\"\"שיבוץ אופטימלי (מינימום עלות) בכוח גס — למטריצות קטנות.\"\"\"",
        "    n,m = cost.shape; best=None; best_c=np.inf",
        "    rows=range(n)",
        "    for perm in permutations(range(m), n):",
        "        c=sum(cost[i,perm[i]] for i in rows)",
        "        if c<best_c: best_c=c; best=perm",
