        "$$d^2 = (z-\\hat z)^T S^{-1} (z-\\hat z) \\le \\gamma$$",
        "כאשר $S=HPH^T+R$ היא שונות החדשה (innovation). $d^2$ מתפלג $\\chi^2$ עם דרגות חופש כמספר ממדי המדידה.",
